INITIALS = ['zh', 'ch', 'sh', 'b', 'p', 'm', 'f', 'd', 't', 'n', 'l',
            'g', 'k', 'h', 'j', 'q', 'x', 'r', 'z', 'c', 's', 'y', 'w']
TONE_CHARS = set('āáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜ')
WHOLE_SYLLABLES = set('zhi chi shi ri zi ci si yi wu yu ye yue yuan yin yun ying'.split())
TRI_FINALS = set('ia iao ian iang iong ua uo uai uan uang ueng üan iong'.split())
FORCE_SINGLE = set('一不')


def has_tone(s):
    return any(ch in TONE_CHARS for ch in s)


def char_pinyin(char, word):
    """按组词给单字定音；轻声或变调时回退到单字本调。"""
    if char in FORCE_SINGLE:
        return pinyin(char, style=Style.TONE)[0][0]
    py = pinyin(word, style=Style.TONE)
    idx = word.index(char)
    if idx < len(py):
        cand = py[idx][0]
        if has_tone(cand):
            return cand
    cand = pinyin(char, style=Style.TONE)[0][0]
    if has_tone(cand):
        return cand
    # 极少数单字默认读轻声（如「子」），从多音字候选里取本调
    for alt in pinyin(char, style=Style.TONE, heteronym=True)[0]:
        if has_tone(alt):
            return alt
    return ''


def split_pinyin(py):
    for ini in INITIALS:
        if py.startswith(ini):
            return ini, py[len(ini):]
    return '', py


def make_tip(ini, final, full):
    base = ''.join(ch for ch in final)
    # 去调（用 JS 侧同款字符表）
    tone_map = {}
    for base_ch, group in {'a': 'āáǎà', 'o': 'ōóǒò', 'e': 'ēéěè',
                           'i': 'īíǐì', 'u': 'ūúǔù', 'ü': 'ǖǘǚǜ'}.items():
        for ch in group:
            tone_map[ch] = base_ch
    raw = ''.join(tone_map.get(ch, ch) for ch in final)
    bare = full
    if bare in WHOLE_SYLLABLES:
        return '「' + full + '」是整体认读音节，要整个记住，不用拼哦'
    if ini in ('j', 'q', 'x') and raw.startswith('u'):
        return '小 ü 碰到 j、q、x，去掉两点还读 ü：' + ini + ' + ' + final + ' → ' + full
    if ini in ('n', 'l') and raw.startswith('ü'):
        return 'ü 上的两点不能丢：' + ini + ' + ' + final + ' → ' + full
    if raw in TRI_FINALS:
        return '这是三拼音节，中间的介音要读得又轻又短：' + ini + ' + ' + final
    return ''


def js_str(s):
    return json.dumps(s, ensure_ascii=False)


def main():
    seen = {}
    skipped, dup, bad = [], [], []
    grades = {g: [] for g in range(1, 7)}

    for g in range(1, 7):
        tokens = TABLES[g].split()
        for tok in tokens:
            if ':' not in tok:
                bad.append('格式错误: ' + tok)
                continue
            char, word = tok.split(':', 1)
            if len(char) != 1 or char not in word:
                bad.append('组词不含该字: ' + tok)
                continue
            if char in seen:
                dup.append(char + '(原属' + str(seen[char]) + '年级, 又见于' + str(g) + '年级)')
                continue
            full = char_pinyin(char, word)
            if not full:
                skipped.append(char + ':' + word + '(无带调读音/轻声)')
                continue
            ini, final = split_pinyin(full)
            if not ini or not final or not has_tone(final):
                skipped.append(char + ':' + word + '(' + full + ' 零声母或韵母无调)')
                continue
            seen[char] = g
            e, s, legacy_tip = LEGACY.get(char, ('📖', '', ''))
            tip = legacy_tip or make_tip(ini, final, full)
            item = {'c': char, 'i': ini, 'f': final, 'w': word, 'e': e, 'g': g}
            if s:
                item['s'] = s
            if tip:
                item['tip'] = tip
            grades[g].append(item)

    # ---------- 生成 JS ----------
    units_js = []
    for n, name, emoji, color in GRADE_META:
        words = grades[n]
        lines = []
        for w in words:
            parts = ['c:' + js_str(w['c']), 'i:' + js_str(w['i']), 'f:' + js_str(w['f']),
                     'w:' + js_str(w['w']), 'e:' + js_str(w['e'])]
            if 's' in w:
                parts.append('s:' + js_str(w['s']))
            if 'tip' in w:
                parts.append('tip:' + js_str(w['tip']))
            lines.append('        { ' + ', '.join(parts) + ' }')
        units_js.append(
            "    {\n      id: 'g%d', n: %d, name: %s, emoji: %s, color: '%s',\n      words: [\n%s\n      ]\n    }"
            % (n, n, js_str(name), js_str(emoji), color, ',\n'.join(lines))
        )

    tpl = (ROOT / 'tools' / 'data.template.js').read_text(encoding='utf-8')
    out = tpl.replace('/*__UNITS__*/', '[\n' + ',\n'.join(units_js) + '\n  ]')
    OUT.write_text(out, encoding='utf-8', newline='\n')

    total = sum(len(v) for v in grades.values())
    print('生成完成:', OUT)
    print('各年级字数:', {g: len(grades[g]) for g in grades}, '总计', total)
    print('跳过(零声母/轻声):', len(skipped), '、'.join(skipped))
    print('重复字(自动保留低年级):', len(dup), '、'.join(dup[:12]))
    print('格式错误:', len(bad), '、'.join(bad))


if __name__ == '__main__':
    main()
